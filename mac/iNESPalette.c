ines_dword_t  iNES_palette_bgra[MAX_COLORS];


void iNES_palette_init(void)
{
	ines_int_t   i;

	for(i = 0; i < MAX_COLORS; i++)
	{
		// 内存字节序 B,G,R,0xFF: 在小端序 CPU 上对应的 32bit 值如下
		iNES_palette_bgra[i] = ((ines_dword_t)0xFF << 24)
							 | ((ines_dword_t)iNES_palette[i].r << 16)
							 | ((ines_dword_t)iNES_palette[i].g << 8)
							 | ((ines_dword_t)iNES_palette[i].b);
	}
}


void iNES_palette_to_bgra(const ines_byte_t* pSrc, ines_byte_t* pDst,
						  ines_int_t width, ines_int_t height)
{
	ines_int_t   x, y;

	if(pSrc == NULL || pDst == NULL || width <= 0 || height <= 0)
		return;

	// 源是自底向上的 DIB 布局(第 0 行是屏幕最下面一行), 目标是自顶向下,
	// 因此按行翻转写入。
	for(y = 0; y < height; y++)
	{
		const ines_byte_t*  pRow = pSrc + (ines_size_t)(height - 1 - y) * width;
		ines_dword_t*       pLine = (ines_dword_t*)(pDst + (ines_size_t)y * width * 4);

		for(x = 0; x < width; x++)
		{
			ines_dword_t  color = pRow[x];

			if(color >= MAX_COLORS)
				color = 0;
			pLine[x] = iNES_palette_bgra[color];
		}
	}
}
